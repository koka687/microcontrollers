#include <htc.h>
#include <string.h>

#define _XTAL_FREQ 4000000

#define RS RB0
#define RW RB1
#define E  RB2

// ?????? ????????? ?? ????? A (???????? ?????? ? 0 ??? ??????????)
#define BTN_ESC  RA0
#define BTN_UP   RA1
#define BTN_DOWN RA2
#define BTN_OK   RA3

void lcd_com(unsigned char cmd) {
    RS = 0; RW = 0;
    PORTD = cmd;
    E = 1; __delay_us(5); E = 0;
    __delay_ms(2);
}

void lcd_data(unsigned char data) {
    RS = 1; RW = 0;
    PORTD = data;
    E = 1; __delay_us(5); E = 0;
    __delay_ms(2);
}

void lcd_init(void) {
    __delay_ms(40);
    lcd_com(0x38);
    lcd_com(0x0C);
    lcd_com(0x01);
    __delay_ms(2);
    lcd_com(0x06);
}

void lcd_puts(const char *str) {
    unsigned char i;
    for(i = 0; i < strlen(str); i++) {
        lcd_data(str[i]);
    }
}

void show_start_screen(void) {
    lcd_com(0x01);
    __delay_ms(2);
    lcd_com(0x84);
    lcd_puts("-MENU-");
    lcd_com(0xC2);
    lcd_puts("press <OK>");
}

void show_main_menu(unsigned char flag) {
    lcd_com(0x01);
    __delay_ms(2);
    if (flag == 0) {
        lcd_com(0x82); lcd_puts("> OPEN");
        lcd_com(0xC2); lcd_puts("  CLOSE");
    } else {
        lcd_com(0x82); lcd_puts("  OPEN");
        lcd_com(0xC2); lcd_puts("> CLOSE");
    }
}

