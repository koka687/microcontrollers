#include <htc.h>
#include <string.h>

#define _XTAL_FREQ 4000000

#define RS RB0
#define RW RB1
#define E  RB2

// ??????????? ????????? ????? ???? ???????
#define LED_GREEN RC6
#define LED_RED   RC7

// ????????? ?????? ??????? Umax ? ????? ??????? ?????? (350 = 3.50 ?)
#define U_MAX_THRESHOLD 350

void lcd_com(unsigned char cmd) {
    RS = 0; RW = 0;
    PORTD = cmd;
    E = 1; __delay_us(5); E = 0;
    __delay_ms(2);
}

void lcd_data(unsigned char data) {
    RS = 1; RW = 0;
    PORTD = data;
    E = 1; __delay_us(5); E = 0;
    __delay_ms(2);
}

void lcd_init(void) {
    __delay_ms(40);
    lcd_com(0x38);
    lcd_com(0x0C);
    lcd_com(0x01);
    __delay_ms(2);
    lcd_com(0x06);
}

void lcd_puts(const char *str) {
    unsigned char i;
    for (i = 0; i < strlen(str); i++) {
        lcd_data(str[i]);
    }
}

unsigned int read_adc(void) {
    unsigned int result;
    ADON = 1;
    __delay_us(40);
    GO_DONE = 1;
    while (GO_DONE);
    result = ((unsigned int)ADRESH << 8) | ADRESL;
    ADIF = 0;
    ADON = 0;
    return result;
}

void main(void) {
    unsigned int adc_val, u_int;
    float U;
    unsigned char odn, d1, d2;

    TRISA = 0b00000001;  // RA0/AN0 ? ?????????? ????
    TRISB = 0x00;        // ????????? ???
    TRISC = 0x00;        // ?????? ?? ??????????? ???? (RC6 ? ???????, RC7 ? ????????)
    TRISD = 0x00;        // ???? ????? ???

    PORTB = 0x00;
    PORTC = 0x00;
    PORTD = 0x00;

    ADCON1 = 0b10001110; // ????? ????????????, RA0 ? ??????????
    ADCON0 = 0b01000000; // Fosc/8, ????? 0

    lcd_init();

    // ?????? ?? ???: 1-? ????? ? ??????? ??????? ? ?????, 2-? ????? ? ???? ????
    lcd_com(0x80);
    lcd_puts("U= .  V Max=3.5V");

    while (1) {
        adc_val = read_adc();
        U = adc_val * ((float)5.0 / 1023.0);
        u_int = (unsigned int)(U * 100.0 + 0.5);

        odn = (u_int / 100) % 10;
        d1  = (u_int / 10) % 10;
        d2  = u_int % 10;

        // ????????? ???????? ??????? ? 1-?? ?????
        lcd_com(0x82);
        lcd_data(odn + 0x30);
        lcd_com(0x84);
        lcd_data(d1 + 0x30);
        lcd_data(d2 + 0x30);

        // ????????? ?????? Umax ?? ??????????? ???? (???????????? ? ??????? ?? ???)
        lcd_com(0xC0);
        if (u_int <= U_MAX_THRESHOLD) {
            LED_GREEN = 1;
            LED_RED = 0;
            lcd_puts("RELAY: ON  (OK) ");
        } else {
            LED_GREEN = 0;
            LED_RED = 1;
            lcd_puts("RELAY: OFF (MAX)");
        }

        __delay_ms(100);
    }
}
