#include <htc.h>
#include <string.h>

#define _XTAL_FREQ 4000000

#define RS RB0
#define RW RB1
#define E  RB2

void lcd_com(unsigned char cmd) {
    RS = 0; RW = 0;
    PORTD = cmd;
    E = 1; __delay_us(5); E = 0;
    __delay_ms(2);
}

void lcd_data(unsigned char data) {
    RS = 1; RW = 0;
    PORTD = data;
    E = 1; __delay_us(5); E = 0;
    __delay_ms(2);
}

void lcd_init(void) {
    __delay_ms(40);
    lcd_com(0x38); // 8-???, 2 ?????
    lcd_com(0x0C); // ??????? ?????????, ??? ???????
    lcd_com(0x01); // ????????
    __delay_ms(2);
    lcd_com(0x06); // ?????????????
}

void lcd_puts(const char *str) {
    unsigned char i;
    for(i = 0; i < strlen(str); i++) {
        lcd_data(str[i]);
    }
}

